import assert from 'node:assert/strict';
import { sample } from '../../shell/desktop/modules/bar/ApplicationTraffic.mjs';
const socket = (id, rxBytes, txBytes, name = 'browser', pid = 10) => ({id, rxBytes, txBytes, name, pid});
let first = sample({}, [socket(1, 100, 20), socket(2, 1000, 100)], 1000);
assert.equal(first.rows[0].download, 0, 'first read is a baseline, not lifetime traffic');
let next = sample(first.previous, [socket(1, 500, 220), socket(2, 1200, 150)], 2000);
assert.equal(next.rows[0].download, 600);
assert.equal(next.rows[0].upload, 250);
let closed = sample(next.previous, [socket(1, 700, 250)], 3000);
assert.equal(closed.rows[0].download, 200, 'closed sockets must not subtract their lifetime bytes');
assert.equal(sample(closed.previous, [socket(1, 10, 1)], 4000).rows[0].download, 0, 'reset counters need a baseline');
assert.equal(sample(closed.previous, [socket(1, 900, 350)], 10000).rows[0].download, 0, 'stale reads need a fresh baseline');
const duplicate = sample(first.previous, [socket(1, 500, 220), socket(1, 500, 220)], 2000);
assert.equal(duplicate.rows[0].download, 400, 'shared socket must not be double counted');
const sortBaseline = sample({}, [socket(1, 100, 20), socket(2, 1000, 100, 'mail', 20)], 1000);
const sorted = sample(sortBaseline.previous, [socket(1, 500, 220), socket(2, 9000, 1000, 'mail', 20)], 2000);
assert.equal(sorted.rows[0].name, 'mail');
assert.deepEqual(sample(next.previous, [], 3000).rows, []);
console.log('application traffic: socket deltas, aggregation, sorting, counter resets and close/reopen passed');
